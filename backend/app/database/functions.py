def execute_function(function_name: str, db: Session, **kwargs) -> Dict:
    """Execute a registered function safely."""
    if function_name not in FUNCTION_REGISTRY:
        return {
            "status": "error",
            "message": f"Function '{function_name}' is not in the registry.",
            "data": None,
        }
    entry = FUNCTION_REGISTRY[function_name]
    fn = entry["function"]
    # Check for missing required parameters
    for req in entry["required"]:
        if req not in kwargs or not kwargs[req]:
            return {
                "status": "not_found",
                "message": f"Required parameter '{req}' is missing or not recognized in the database.",
                "data": None,
            }
    # Remove None kwargs to use function defaults
    clean_kwargs = {k: v for k, v in kwargs.items() if v is not None}
    try:
        result = fn(db=db, **clean_kwargs)
        if result.get("status") != "success" or not result.get("data"):
            return result

        years = set()

        def collect_years(value):
            if isinstance(value, dict):
                for key, item in value.items():
                    if key in {"assessment_year", "year"} and str(item).isdigit():
                        years.add(str(item))
                    elif key in {"year_1", "year_2"} and isinstance(item, dict):
                        collect_years(item)
                    else:
                        collect_years(item)
            elif isinstance(value, list):
                for item in value:
                    collect_years(item)

        collect_years(result["data"])
        for key in ("assessment_year", "year1", "year2"):
            if clean_kwargs.get(key) and str(clean_kwargs[key]).isdigit():
                years.add(str(clean_kwargs[key]))

        provenance = []
        for year in sorted(years):
            source = repo.get_source_provenance(db, year)
            if source:
                provenance.append(source)

        if provenance:
            result["provenance"] = provenance
            result["source"] = provenance[0]["source_document"]
        return result
    except Exception as exc:
        return {
            "status": "not_found",
            "message": f"Database function could not find matching records: {str(exc)}",
            "data": None,
        }


def get_registry_metadata() -> List[Dict]:
    """Return registry info without function objects."""
    result = []
    for name, info in FUNCTION_REGISTRY.items():
        result.append({
            "function_name": name,
            "description": info["description"],
            "parameters": info["parameters"],
            "required_parameters": info["required"],
            "category": info["category"],
            "example_question": info["example"],
            "data_available": info["data_available"],
        })
    return result
