def _not_found(msg: str) -> Dict:
    return {"status": "not_found", "message": msg, "data": None}


def _error(msg: str) -> Dict:
    return {"status": "error", "message": msg, "data": None}


def _ok(data: Any, meta: Dict = None) -> Dict:
    result = {"status": "success", "data": data}
    if meta:
        result.update(meta)
    return result


