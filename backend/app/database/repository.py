def _is_state_level_district(name: Optional[str]) -> bool:
    if not name:
        return True
    cleaned = str(name).strip().lower()
    return cleaned in {
        "",
        "none",
        "null",
        "state-level",
        "state-level (no district)",
        "state-level (all districts)",
        "state level",
        "all districts",
        "state",
        "state wide",
        "state-wide",
    }


def _normalize_year_str(year_val: Any) -> Optional[str]:
    if year_val is None:
        return None
    s = str(year_val).strip()
    match = re.search(r'\b(20\d\d)\b', s)
    if match:
        return match.group(1)
    try:
        val = int(float(s))
        if 1990 <= val <= 2035:
            return str(val)
    except Exception:
        pass
    return s if s else None


def _resolve_state(db: Session, state_name: str) -> Optional[State]:
    if not state_name:
        return None
    sname = str(state_name).strip()
    q = db.query(State).filter(
        State.name.ilike(f"%{sname}%")
    ).first()
    if q:
        return q

    # Check state aliases in GeographicMaster
    for gm in db.query(GeographicMaster).filter(GeographicMaster.entity_type == "state").all():
        aliases = [a.strip().lower() for a in (gm.aliases or "").split(",") if a.strip()]
        aliases.append(gm.canonical_name.lower())
        if sname.lower() in aliases:
            q2 = db.query(State).filter(State.name.ilike(f"%{gm.canonical_name}%")).first()
            if q2:
                return q2
    return None


def _resolve_district(db: Session, district_name: str, state_id: int = None):
    if not district_name or _is_state_level_district(district_name):
        return None
    dname = str(district_name).strip()

    # Build candidates (e.g., "Tirupati (Chittoor)" -> ["Tirupati (Chittoor)", "Tirupati", "Chittoor"])
    candidates = [dname]
    match = re.search(r'^(.*?)\s*\((.*?)\)$', dname)
    if match:
        main_part = match.group(1).strip()
        paren_part = match.group(2).strip()
        if main_part:
            candidates.append(main_part)
        if paren_part:
            candidates.append(paren_part)

    for cand in candidates:
        q = db.query(District).filter(
            District.name.ilike(f"%{cand}%")
        )
        if state_id:
            q = q.filter(District.state_id == state_id)
        dist = q.first()
        if dist:
            return dist

    # Reverse check against all districts in state
    all_dists = db.query(District)
    if state_id:
        all_dists = all_dists.filter(District.state_id == state_id)
    for dist in all_dists.all():
        db_name = dist.name.lower()
        for cand in candidates:
            c_low = cand.lower()
            if c_low in db_name or db_name in c_low:
                return dist

    # Check district aliases in GeographicMaster
    gm_query = db.query(GeographicMaster).filter(GeographicMaster.entity_type == "district")
    if state_id:
        st = db.query(State).filter(State.id == state_id).first()
        if st:
            gm_query = gm_query.filter(GeographicMaster.state_name.ilike(st.name))
    for gm in gm_query.all():
        aliases = [a.strip().lower() for a in (gm.aliases or "").split(",") if a.strip()]
        aliases.append(gm.canonical_name.lower())
        for cand in candidates:
            if cand.lower() in aliases:
                q2 = db.query(District).filter(District.name.ilike(f"%{gm.canonical_name}%"))
                if state_id:
                    q2 = q2.filter(District.state_id == state_id)
                dist2 = q2.first()
                if dist2:
                    return dist2
    return None


def _resolve_year(db: Session, year: str) -> Optional[AssessmentYear]:
    if not year:
        return None
    norm = _normalize_year_str(year)
    if not norm:
        return None
    return db.query(AssessmentYear).filter(
        AssessmentYear.year == norm
    ).first()


