def get_latest_verified_record(
    db: Session,
    state: Optional[str] = None,
    district: Optional[str] = None,
    parameter: Optional[str] = None,
) -> Optional[Dict]:
    """
    Find the latest verified assessment record for a given location and parameter.
    Used for intelligent follow-ups and dynamic unavailable-year recommendations.
    """
    q = db.query(GroundwaterResource, AssessmentYear).join(
        AssessmentYear, GroundwaterResource.assessment_year_id == AssessmentYear.id
    ).filter(
        GroundwaterResource.is_verified.is_(True)
    )

    st_obj = None
    if state:
        st_obj = _resolve_state(db, state)
        if st_obj:
            q = q.filter(GroundwaterResource.state_id == st_obj.id)

    dist_obj = None
    if district and not _is_state_level_district(district):
        dist_obj = _resolve_district(db, district, st_obj.id if st_obj else None)
        if dist_obj:
            q = q.filter(GroundwaterResource.district_id == dist_obj.id)

    param_clean = (parameter or "").lower()
    if any(k in param_clean for k in ["recharge", "get_groundwater_recharge"]):
        q = q.filter(GroundwaterResource.total_annual_recharge.isnot(None))
    elif any(k in param_clean for k in ["extractable", "get_extractable_groundwater"]):
        q = q.filter(GroundwaterResource.annual_extractable_groundwater.isnot(None))
    elif any(k in param_clean for k in ["stage", "get_stage_of_extraction"]):
        q = q.filter(GroundwaterResource.stage_of_extraction_pct.isnot(None))
    elif any(k in param_clean for k in ["categor", "get_assessment_category"]):
        q = q.filter(GroundwaterResource.assessment_category.isnot(None))
    elif any(k in param_clean for k in ["extraction", "get_groundwater_extraction"]):
        q = q.filter(GroundwaterResource.total_annual_extraction.isnot(None))

    rows = q.order_by(AssessmentYear.year.desc()).all()
    if not rows:
        return None

    if dist_obj:
        rec, yr_obj = rows[0]
        val = None
        param_label = "extraction"
        if any(k in param_clean for k in ["recharge", "get_groundwater_recharge"]):
            val = rec.total_annual_recharge
            param_label = "recharge"
        elif any(k in param_clean for k in ["extractable", "get_extractable_groundwater"]):
            val = rec.annual_extractable_groundwater
            param_label = "extractable groundwater"
        elif any(k in param_clean for k in ["stage", "get_stage_of_extraction"]):
            val = rec.stage_of_extraction_pct
            param_label = "stage of extraction"
        elif any(k in param_clean for k in ["categor", "get_assessment_category"]):
            val = rec.assessment_category
            param_label = "category"
        else:
            val = rec.total_annual_extraction
            param_label = "extraction"

        loc_name = _format_location_label(dist_obj.name, st_obj.name if st_obj else None)
        return {
            "location": loc_name,
            "district": dist_obj.name,
            "state": st_obj.name if st_obj else None,
            "latest_year": yr_obj.year,
            "value": val,
            "unit": rec.unit or "Ham",
            "parameter": param_label,
            "verification_status": rec.verification_status or "VERIFIED",
            "source_document": rec.source_document or "CGWB National Compilation",
            "source_agency": rec.source_agency or "Central Ground Water Board (CGWB)",
        }
    else:
        # State-level aggregate across districts for the latest available year
        latest_yr_str = rows[0][1].year
        yr_rows = [r[0] for r in rows if r[1].year == latest_yr_str]
        param_label = "extraction"
        if any(k in param_clean for k in ["recharge", "get_groundwater_recharge"]):
            vals = [r.total_annual_recharge for r in yr_rows if r.total_annual_recharge is not None]
            val = round(sum(vals), 2) if vals else None
            param_label = "recharge"
        elif any(k in param_clean for k in ["extractable", "get_extractable_groundwater"]):
            vals = [r.annual_extractable_groundwater for r in yr_rows if r.annual_extractable_groundwater is not None]
            val = round(sum(vals), 2) if vals else None
            param_label = "extractable groundwater"
        elif any(k in param_clean for k in ["stage", "get_stage_of_extraction"]):
            vals = [r.stage_of_extraction_pct for r in yr_rows if r.stage_of_extraction_pct is not None]
            val = round(sum(vals) / len(vals), 2) if vals else None
            param_label = "stage of extraction"
        else:
            vals = [r.total_annual_extraction for r in yr_rows if r.total_annual_extraction is not None]
            val = round(sum(vals), 2) if vals else None
            param_label = "extraction"

        loc_name = st_obj.name if st_obj else "National"
        first_rec = yr_rows[0]
        return {
            "location": loc_name,
            "district": None,
            "state": st_obj.name if st_obj else None,
            "latest_year": latest_yr_str,
            "value": val,
            "unit": "%" if "stage" in param_label else (first_rec.unit or "Ham"),
            "parameter": param_label,
            "verification_status": "VERIFIED",
            "source_document": first_rec.source_document or "CGWB National Compilation",
            "source_agency": first_rec.source_agency or "Central Ground Water Board (CGWB)",
        }


