def compare_locations(
    db: Session, state1: str, district1: str,
    state2: str, district2: str,
    parameter: str, assessment_year: str = None
) -> Dict:
    """Compare two locations on a given groundwater parameter."""
    PARAM_FIELD_MAP = {
        "recharge": "total_annual_recharge",
        "extraction": "total_annual_extraction",
        "extractable": "annual_extractable_groundwater",
        "stage": "stage_of_extraction_pct",
        "category": "assessment_category",
    }
    field = None
    for key, val in PARAM_FIELD_MAP.items():
        if key in parameter.lower():
            field = val
            break
    if not field:
        return _error(f"Unknown parameter '{parameter}' for comparison. Choose: recharge, extraction, extractable, stage, category.")

    results = {}
    provs = []
    for state_name, dist_name in [(state1, district1), (state2, district2)]:
        st = _resolve_state(db, state_name)
        if not st:
            return _not_found("Verified data for this location, parameter and assessment year is not currently available in the database.")
        dist = _resolve_district(db, dist_name, st.id)
        if not dist:
            return _not_found("Verified data for this location, parameter and assessment year is not currently available in the database.")
        q = db.query(GroundwaterResource).filter(
            GroundwaterResource.district_id == dist.id,
            GroundwaterResource.is_verified.is_(True),
        )
        if assessment_year:
            yr = _resolve_year(db, assessment_year)
            if not yr:
                return _not_found("Verified data for this location, parameter and assessment year is not currently available in the database.")
            q = q.filter(GroundwaterResource.assessment_year_id == yr.id)
        rec = q.order_by(GroundwaterResource.assessment_year_id.desc()).first()
        if not rec or getattr(rec, field) is None:
            return _not_found("Verified data for this location, parameter and assessment year is not currently available in the database.")

        actual_yr = db.query(AssessmentYear).filter(
            AssessmentYear.id == rec.assessment_year_id
        ).first()
        results[f"{dist.name}, {st.name}"] = {
            "district": dist.name,
            "state": st.name,
            "assessment_year": actual_yr.year if actual_yr else assessment_year,
            "assessment_unit_level": rec.assessment_unit_level or "District",
            "parameter": parameter,
            "value": getattr(rec, field),
            "unit": "Ham" if field != "stage_of_extraction_pct" else "%",
            "verification_status": rec.verification_status or "VERIFIED",
        }
        provs.append(_build_provenance(rec, db))

    return _ok({
        "comparison": results,
        "parameter": parameter,
        "verification_status": "VERIFIED",
    }, {
        "source": provs[0]["source_document"] if provs else "CGWB National Compilation",
        "source_agency": provs[0]["source_agency"] if provs else "Central Ground Water Board (CGWB)",
        "provenance": provs,
    })


