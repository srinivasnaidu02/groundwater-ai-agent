def _format_location_label(dist_name: Optional[str], st_name: Optional[str]) -> str:
    """Format clean location label avoiding redundancies like 'South Delhi, Delhi' or 'Chandigarh, Chandigarh'."""
    dist = (dist_name or "").strip()
    st = (st_name or "").strip()
    if dist and st:
        dist_l = dist.lower()
        st_l = st.lower()
        if dist_l == st_l or dist_l.endswith(st_l):
            return dist
        return f"{dist}, {st}"
    return dist or st or "N/A"


def _build_provenance(rec: GroundwaterResource, db: Session = None) -> Dict:
    """Build rich record-level provenance metadata matching Section 4 & 8 specifications."""
    src = rec.source_dataset
    yr = rec.assessment_year.year if rec.assessment_year else ""
    dist_name = rec.district.name if rec.district else rec.assessment_unit_name
    st_name = rec.state.name if rec.state else ""
    loc_label = _format_location_label(dist_name, st_name)

    field_labels = {
        "total_annual_recharge": "total_annual_recharge_ham",
        "annual_extractable_groundwater": "annual_extractable_groundwater_ham",
        "annual_extraction_irrigation": "extraction_irrigation_ham",
        "annual_extraction_industrial": "extraction_industrial_ham",
        "annual_extraction_domestic": "extraction_domestic_ham",
        "total_annual_extraction": "total_annual_extraction_ham",
        "stage_of_extraction_pct": "stage_of_extraction_pct",
        "assessment_category": "assessment_category",
    }
    verified_fields = sorted([
        label for field, label in field_labels.items()
        if getattr(rec, field) is not None
    ])

    source_doc = rec.source_document or (src.name if src else "National Compilation on Dynamic Ground Water Resources of India")
    source_agency = rec.source_agency or (src.source_agency if src else "Central Ground Water Board (CGWB), Department of Water Resources, River Development & Ganga Rejuvenation, Ministry of Jal Shakti, Government of India")
    source_url = rec.source_url or (src.source_url if src else None)
    orig_file = rec.original_filename or (src.original_filename if src else None)

    return {
        "dataset_name": source_doc,
        "source_agency": source_agency,
        "source_document": source_doc,
        "source_document_url": source_url,
        "assessment_year": yr,
        "publication_year": src.publication_year if src else (int(yr) if str(yr).isdigit() else None),
        "data_year": src.data_year if src else yr,
        "original_filename": orig_file,
        "sha256_checksum": rec.sha256_checksum,
        "source_page_table": rec.source_page_table,
        "assessment_unit_name": dist_name or loc_label,
        "assessment_unit_level": rec.assessment_unit_level or "District",
        "location": loc_label,
        "unit": rec.unit or "Ham",
        "verification_status": rec.verification_status or ("VERIFIED" if rec.is_verified else "UNVERIFIED"),
        "verification_evidence": rec.verification_evidence,
        "dataset_fully_verified": bool(src.is_verified) if src else False,
        "record_verified": bool(rec.is_verified),
        "verified_record_count": 1,
        "verified_fields": verified_fields,
    }


def get_source_provenance(db: Session, year: str) -> Optional[Dict]:
    source = (
        db.query(SourceDataset)
        .filter(SourceDataset.assessment_period == str(year))
        .order_by(SourceDataset.id.desc())
        .first()
    )
    if not source:
        return None
    verified_records = db.query(GroundwaterResource).filter(
        GroundwaterResource.source_dataset_id == source.id,
        GroundwaterResource.is_verified.is_(True),
    ).all()
    field_labels = {
        "total_annual_recharge": "total_annual_recharge_ham",
        "annual_extractable_groundwater": "annual_extractable_groundwater_ham",
        "annual_extraction_irrigation": "extraction_irrigation_ham",
        "annual_extraction_industrial": "extraction_industrial_ham",
        "annual_extraction_domestic": "extraction_domestic_ham",
        "total_annual_extraction": "total_annual_extraction_ham",
        "stage_of_extraction_pct": "stage_of_extraction_pct",
        "assessment_category": "assessment_category",
    }
    verified_fields = sorted({
        label
        for record in verified_records
        for field, label in field_labels.items()
        if getattr(record, field) is not None
    })
    return {
        "assessment_year": str(year),
        "publication_year": source.publication_year,
        "data_year": source.data_year,
        "source_agency": source.source_agency,
        "source_document": source.name,
        "source_document_url": source.source_url,
        "dataset_fully_verified": bool(source.is_verified),
        "verification_status": "VERIFIED" if verified_records else source.verification_status,
        "record_verified": bool(verified_records),
        "verified_record_count": len(verified_records),
        "verified_fields": verified_fields,
    }


