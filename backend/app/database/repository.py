def get_data_coverage(db: Session) -> Dict:
    """Return comprehensive data coverage statistics across the database."""
    total_records = db.query(GroundwaterResource).filter(
        GroundwaterResource.is_verified.is_(True)
    ).count()
    states = (
        db.query(State)
        .join(GroundwaterResource, GroundwaterResource.state_id == State.id)
        .filter(GroundwaterResource.is_verified.is_(True))
        .distinct()
        .order_by(State.name.asc())
        .all()
    )
    years = (
        db.query(AssessmentYear)
        .join(
            GroundwaterResource,
            GroundwaterResource.assessment_year_id == AssessmentYear.id,
        )
        .filter(GroundwaterResource.is_verified.is_(True))
        .distinct()
        .order_by(AssessmentYear.year.asc())
        .all()
    )

    state_details = []
    for s in states:
        dists = (
            db.query(District)
            .join(GroundwaterResource, GroundwaterResource.district_id == District.id)
            .filter(
                District.state_id == s.id,
                GroundwaterResource.is_verified.is_(True),
            )
            .distinct()
            .count()
        )
        recs_count = db.query(GroundwaterResource).filter(
            GroundwaterResource.state_id == s.id,
            GroundwaterResource.is_verified.is_(True),
        ).count()
        state_details.append({
            "state_id": s.id,
            "state_name": s.name,
            "district_count": dists,
            "record_count": recs_count,
        })

    return _ok({
        "total_records": total_records,
        "total_states": len(states),
        "total_districts": sum(state["district_count"] for state in state_details),
        "available_years": [y.year for y in years],
        "states": state_details,
    }, {"source": "CGWB & IN-GRES National Database Catalog"})


